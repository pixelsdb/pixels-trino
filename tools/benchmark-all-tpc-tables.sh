#!/usr/bin/env bash
# Full-column JDBC INSERT benchmark with isolated engine, plugin, and backend JVMs.
set -euo pipefail
TRINO=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
export SQL_E2E_MAIN_CLASS=io.pixelsdb.pixels.trino.testing.AllTpcTablesBenchmark
export TPCH_SCHEMA=${TPCH_SCHEMA:-sf10}
export TPCDS_SCHEMA=${TPCDS_SCHEMA:-sf10}
export SQL_E2E_PASS_PATTERN='ALL_TPC_TABLES_INSERT_PASS tables=32'
export SQL_E2E_TIMEOUT_SECONDS=${SQL_E2E_TIMEOUT_SECONDS:-14400}
export SQL_E2E_BACKEND_HEAP=${SQL_E2E_BACKEND_HEAP:-6g}
export SQL_E2E_ENGINE_HEAP=${SQL_E2E_ENGINE_HEAP:-6g}
export SQL_E2E_BACKEND_STOP_TIMEOUT_SECONDS=${SQL_E2E_BACKEND_STOP_TIMEOUT_SECONDS:-180}
export PIXELS_SQL_FIXTURE_ROUTE_COUNT=${PIXELS_SQL_FIXTURE_ROUTE_COUNT:-4}
export PIXELS_SQL_FIXTURE_REPRESENTATION=${PIXELS_SQL_FIXTURE_REPRESENTATION:-FILE}
export PIXELS_SQL_FIXTURE_COMMIT_ACK=${PIXELS_SQL_FIXTURE_COMMIT_ACK:-DURABLE}
export PIXELS_SQL_FIXTURE_MAX_BATCH_ROWS=${PIXELS_SQL_FIXTURE_MAX_BATCH_ROWS:-65536}
# Leave room for the RPC envelope below the default gRPC inbound message limit.
export PIXELS_SQL_FIXTURE_MAX_BATCH_BYTES=${PIXELS_SQL_FIXTURE_MAX_BATCH_BYTES:-1048576}
export PIXELS_SQL_FIXTURE_MAX_PREPARED_ROWS=${PIXELS_SQL_FIXTURE_MAX_PREPARED_ROWS:-20000000}
export PIXELS_SQL_FIXTURE_MAX_STATE_BYTES=${PIXELS_SQL_FIXTURE_MAX_STATE_BYTES:-1073741824}
export PIXELS_SQL_FIXTURE_WAL_MAX_BYTES=${PIXELS_SQL_FIXTURE_WAL_MAX_BYTES:-68719476736}
export PIXELS_SQL_FIXTURE_FILE_MAX_BYTES=${PIXELS_SQL_FIXTURE_FILE_MAX_BYTES:-134217728}
export ALL_TPC_VISIBILITY_TIMEOUT_SECONDS=${ALL_TPC_VISIBILITY_TIMEOUT_SECONDS:-1800}
export ALL_TPC_RESUME=false
export ALL_TPC_VERIFY_ONLY=false
export ALL_TPC_TRANSACTION_ROWS=${ALL_TPC_TRANSACTION_ROWS:-10000000}
export ALL_TPC_BARRIER_EACH_TRANSACTION=false
exec bash "$TRINO/tools/benchmark-tpch-tpcds-insert.sh" "$@"
